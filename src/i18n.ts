export function formatCurrencyPKR(amount: number): string {
  const safe = Number.isFinite(amount) ? amount : 0;
  return `Rs. ${safe.toLocaleString('en-PK', { maximumFractionDigits: 0 })}`;
}

export function normalizePhoneForWhatsApp(rawPhone: string): string {
  const digits = rawPhone.replace(/\D/g, '');
  if (!digits) return '';
  if (digits.startsWith('00')) return digits.slice(2);
  if (digits.startsWith('0') && digits.length === 11) return `92${digits.slice(1)}`;
  if (digits.startsWith('3') && digits.length === 10) return `92${digits}`;
  return digits;
}

export function translateUnit(unit: WeightUnit, lang: Language): string {
  if (lang === 'en') return unit;
  switch (unit) {
    case 'Tons':
      return 'ٹن';
    case 'Mann':
      return 'من';
    case 'Kg':
      return 'کلو';
  }
}

export function translateDriverStatus(status: DriverStatus, lang: Language): string {
  if (lang === 'en') return status;
  switch (status) {
    case 'Available':
      return 'دستیاب';
    case 'Loaded':
      return 'لوڈ شدہ';
    case 'Dispatched':
      return 'روانہ';
  }
}

export function translatePaymentType(type: PaymentType, lang: Language): string {
  if (lang === 'en') return type;
  return type === 'To-Pay' ? 'وصولی باقی (To-Pay)' : 'ادا شدہ (Paid)';
}

export function translateCategory(keyOrLabel: string, lang: Language): string {
  const all = [...INCOME_CATEGORIES, ...EXPENSE_CATEGORIES];
  const found = all.find(
    (c) => c.key === keyOrLabel || c.en === keyOrLabel || c.ur === keyOrLabel
  );
  if (!found) return keyOrLabel;
  return lang === 'en' ? found.en : found.ur;
}

